# Data Types: Strings 
x = "hello world"
print(x)  # Output: hello world

# Data Types: Integers (int)
# no need for " "
y = 5
z = 10
print(y)  # Output: 5
print(z)  # Output: 10
print(y + z)  # Output: 15

# Data Types: Floating Point Numbers (float)
k = 3.14
j = 2.71
print(k)  # Output: 3.14
print(j)  # Output: 2.71
print(k + j)  # Output: 5.85

#can add remote integers and floats
print(y + k)  # Output: 8.14

L = [0,1,2]
print(L)  # Output: [0, 1, 2]
print(type(x))  # Output: <class 'str'>
